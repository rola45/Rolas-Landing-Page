export function translateCopy(value: string, language: SiteLanguage): string {
  return language === "en" ? englishCopy[value] ?? value : value;
}

export function translateSiteContent(content: SiteContent, language: SiteLanguage): SiteContent {
  if (language === "es") return content;
  const t = (value: string) => translateCopy(value, language);
  return {
    ...content,
    role: t(content.role),
    heroEyebrow: t(content.heroEyebrow),
    heroTitle: t(content.heroTitle),
    heroDescription: t(content.heroDescription),
    heroCta: t(content.heroCta),
    aboutTitle: t(content.aboutTitle),
    aboutText: t(content.aboutText),
    profileImageAlt: t(content.profileImageAlt),
    heroImageAlt: t(content.heroImageAlt),
    socials: content.socials.map((item) => ({ ...item, label: t(item.label) })),
    services: {
      digital: content.services.digital.map((item) => ({ ...item, title: t(item.title), description: t(item.description) })),
      equipment: content.services.equipment.map((item) => ({ ...item, title: t(item.title), description: t(item.description) })),
    },
    projects: content.projects.map((item) => ({ ...item, title: t(item.title), description: t(item.description), imageAlt: t(item.imageAlt) })),
    processSteps: content.processSteps.map((item) => ({ ...item, title: t(item.title), description: t(item.description) })),
    faqs: content.faqs.map((item) => ({ ...item, question: t(item.question), answer: t(item.answer) })),
    seo: { title: t(content.seo.title), description: t(content.seo.description) },
  };
}
